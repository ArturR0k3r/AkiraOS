"""
gen_logo.py — bake the AkiraOS logo into C arrays for the OS shell.

Output: src/console_shell/ui/akira_logo_data.c, consumed by ui/akira_logo.c.

Each size is cropped to the logo's bounding box and resampled with
premultiplied alpha (no dark fringe on the antialiased edges), then stored as:

  <name>_rgb    RGB565, one uint16 per pixel (0 where fully transparent)
  <name>_alpha  4-bit coverage, two pixels per byte, high nibble first
  <name>_order  (optional) 8-bit growth order for the boot "crystal growth"
                reveal: the shortest path from the starburst's core to the
                pixel *through the crystal*, so every spike grows outward
                along its own length and long spikes finish last.  Floating
                shards that no path reaches fall back to a slightly delayed
                straight-line distance, so they pop in as the front sweeps
                past them.

Usage:
  python3 tools/gen_logo.py                     # defaults below
  python3 tools/gen_logo.py --src assets/logo.png \
      --out src/console_shell/ui/akira_logo_data.c

Needs Pillow + numpy.  Re-run after changing the logo; never hand-edit the
generated file.
"""
import argparse
import heapq
import math

import numpy as np
from PIL import Image

# name, target height in px, emit growth-order map
SIZES = [
    ("akira_logo_l", 120, True),   # boot splash hero
    ("akira_logo_s", 32, False),   # wait screen / system info
]


def rgb565(r, g, b):
    return ((int(r) >> 3) << 11) | ((int(g) >> 2) << 5) | (int(b) >> 3)


def resample(src, height):
    """Crop to content and resize with premultiplied alpha."""
    bbox = src.getbbox()
    crop = src.crop(bbox)
    width = max(1, round(crop.width * height / crop.height))
    small = crop.convert("RGBa").resize((width, height), Image.LANCZOS)
    return np.array(small.convert("RGBA"), dtype=np.int32)


def growth_order(alpha):
    """Geodesic distance from the core through the crystal, 0..254."""
    h, w = alpha.shape
    solid = alpha >= 128
    ys, xs = np.nonzero(alpha >= 230)
    if len(xs) == 0:
        ys, xs = np.nonzero(solid)
    # Core = centroid of the opaque body, snapped to the nearest solid pixel.
    cy, cx = ys.mean(), xs.mean()
    k = int(np.argmin((ys - cy) ** 2 + (xs - cx) ** 2))
    seed = (int(ys[k]), int(xs[k]))

    inf = float("inf")
    dist = np.full((h, w), inf)
    dist[seed] = 0.0
    heap = [(0.0, seed)]
    # 16-neighbourhood (adds knight moves): an 8-neighbour metric makes the
    # growing core visibly octagonal; this keeps the bloom round.
    steps = [(dy, dx, math.hypot(dy, dx))
             for dy in (-2, -1, 0, 1, 2) for dx in (-2, -1, 0, 1, 2)
             if (dy, dx) != (0, 0) and abs(dy) + abs(dx) <= 3
             and not (abs(dy) == 2 and abs(dx) == 0)
             and not (abs(dy) == 0 and abs(dx) == 2)
             and not (abs(dy) == 2 and abs(dx) == 2)]
    while heap:
        d, (y, x) = heapq.heappop(heap)
        if d > dist[y, x]:
            continue
        for dy, dx, cost in steps:
            ny, nx = y + dy, x + dx
            if 0 <= ny < h and 0 <= nx < w and alpha[ny, nx] > 0:
                # Translucent edge pixels are reachable but never relay the
                # path onward, so the front can't leak along the antialiasing.
                if not solid[y, x] and d > 0:
                    continue
                nd = d + cost
                if nd < dist[ny, nx]:
                    dist[ny, nx] = nd
                    heapq.heappush(heap, (nd, (ny, nx)))

    yy, xx = np.mgrid[0:h, 0:w]
    euclid = np.hypot(yy - seed[0], xx - seed[1])
    visible = alpha > 0
    unreached = visible & ~np.isfinite(dist)
    dist[unreached] = euclid[unreached] * 1.15
    top = dist[visible].max() if visible.any() else 1.0
    order = np.full((h, w), 255, dtype=np.int32)
    order[visible] = np.clip(np.round(dist[visible] / top * 254), 0, 254)
    return order, seed


def c_array(ctype, name, values, per_line, fmt):
    out = [f"const {ctype} {name}[{len(values)}] = {{"]
    for i in range(0, len(values), per_line):
        out.append("    " + ", ".join(fmt(v) for v in values[i:i + per_line]) + ",")
    out.append("};")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default="assets/logo.png")
    ap.add_argument("--out", default="src/console_shell/ui/akira_logo_data.c")
    a = ap.parse_args()

    src = Image.open(a.src).convert("RGBA")
    parts = [
        "/*",
        " * Copyright (c) 2026 AkiraOS Contributors",
        " * SPDX-License-Identifier: Apache-2.0",
        " *",
        f" * GENERATED by tools/gen_logo.py from {a.src} — do not edit.",
        " */",
        "",
        "#include <stdint.h>",
        "",
    ]
    for name, height, with_order in SIZES:
        px = resample(src, height)
        h, w = px.shape[:2]
        alpha = px[..., 3]
        a4 = np.clip((alpha + 8) // 17, 0, 15)
        rgb = [0 if a4[y, x] == 0 else rgb565(*px[y, x, :3])
               for y in range(h) for x in range(w)]
        flat_a = a4.flatten().tolist()
        if len(flat_a) % 2:
            flat_a.append(0)
        packed = [(flat_a[i] << 4) | flat_a[i + 1] for i in range(0, len(flat_a), 2)]

        parts.append(f"/* {name}: {w}x{h} */")
        parts.append(f"const uint16_t {name}_w = {w};")
        parts.append(f"const uint16_t {name}_h = {h};")
        parts.append(c_array("uint16_t", f"{name}_rgb", rgb, 12, lambda v: f"0x{v:04X}"))
        parts.append(c_array("uint8_t", f"{name}_alpha", packed, 16, lambda v: f"0x{v:02X}"))
        if with_order:
            order, seed = growth_order(np.where(a4 > 0, alpha, 0))
            parts.append(f"/* growth seed (core) at x={seed[1]} y={seed[0]} */")
            parts.append(f"const uint16_t {name}_core_x = {seed[1]};")
            parts.append(f"const uint16_t {name}_core_y = {seed[0]};")
            parts.append(c_array("uint8_t", f"{name}_order", order.flatten().tolist(), 16,
                                 lambda v: f"{v:3d}"))
        parts.append("")
        print(f"{name}: {w}x{h}" + (" (+order)" if with_order else ""))

    with open(a.out, "w") as f:
        f.write("\n".join(parts))
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
